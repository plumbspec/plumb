package org.plumbspec;

import java.lang.annotation.*;

/**
 * The one authored link, on the test — the JVM's spelling of pytest's {@code proves} marker.
 *
 * <p>A story is proven when a test citing it passed <em>and</em> that test's execution reached
 * wired production code. This annotation is the citation: it is the only thing a human writes to
 * connect a requirement to the code that satisfies it. Everything else Plumb reports is derived
 * from a run.
 *
 * <p>Put it on the test, never on the production code. The thing being judged does not get to
 * claim it passed.
 *
 * <pre>{@code
 * @Test
 * @Proves(value = "APP-142", depth = "wiring")
 * void ordersAreRouted() { ... }
 * }</pre>
 *
 * <p>Repeatable, because a citation is per (test, story) pair: one test may prove several stories,
 * each at its own depth and carrying its own external key.
 *
 * <p>This artifact carries the citation vocabulary and nothing else — no observer, no runner, no
 * dependencies. It is the only part of Plumb intended for a consumer's compile classpath.
 *
 * @see <a href="https://plumbspec.org">plumbspec.org</a>
 */
@Repeatable(Proves.Citations.class)
@Retention(RetentionPolicy.RUNTIME)
@Target({ElementType.METHOD, ElementType.TYPE})
public @interface Proves {

    /**
     * The story this test claims to prove.
     *
     * <p>Opaque to Plumb: a chapter id, a ticket number, a spreadsheet row. Plumb mints no ids and
     * keeps no catalogue of them, so the identifier stays whatever your organisation already uses.
     *
     * @return the story identifier, in the citing project's own vocabulary
     */
    String value();

    /**
     * How deep this test reached.
     *
     * <p>One of {@code unit}, {@code component}, {@code wiring}, {@code standards-integration} or
     * {@code smoke}. This is a <em>claim</em>, and the run either supports it or does not: a test
     * claiming {@code wiring} whose execution never passed through a declared production entry
     * point fails its story rather than quietly downgrading.
     *
     * @return the claimed depth
     */
    String depth();

    /**
     * The consumer's own external key, if their tracker has one.
     *
     * <p>Carried through to the manifest untouched. Plumb never parses it and never assigns
     * meaning to it — it exists so an integrating system keeps its own identifiers rather than
     * adopting Plumb's.
     *
     * @return the external key, or the empty string when there is none
     */
    String ref() default "";

    /**
     * Container for repeated {@link Proves} citations on a single test.
     *
     * <p>Generated by the compiler; you write {@code @Proves} more than once rather than using
     * this directly.
     */
    @Retention(RetentionPolicy.RUNTIME)
    @Target({ElementType.METHOD, ElementType.TYPE})
    @interface Citations {
        /**
         * The citations attached to the annotated element.
         *
         * @return the repeated citations
         */
        Proves[] value();
    }
}
